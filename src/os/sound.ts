import { ZZFX_SAMPLE_RATE, zzfxGenerate, type ZzfxParams } from "./vendor/zzfx";

/** every UI sound JackOS plays, one per kind of action */
export const SOUND_NAMES = ["open", "close", "minimize", "maximize", "error", "menu", "startup"] as const;
/** name of one UI sound, each has a preset in SOUND_PRESETS */
export type SoundName = (typeof SOUND_NAMES)[number];

/** one synthesised note - ZzFX params, starting `at` seconds into the sound */
type Note = { at: number; params: ZzfxParams };

/** one 8-bit square-wave note. shape 0 with curve 0 flattens a sine into a square, like old sound chips */
function chip(frequency: number, length: number, extra: { slide?: number; jump?: number; jumpAt?: number; crush?: number; volume?: number } = {}): ZzfxParams {
  // ZzFX order: volume, randomness, frequency, attack, sustain, release, shape, curve, slide, deltaSlide, pitchJump, pitchJumpTime, ..., bitCrush (index 15)
  return [extra.volume ?? 0.25, 0, frequency, 0, length, 0.02, 0, 0, extra.slide ?? 0, 0, extra.jump ?? 0, extra.jumpAt ?? 0, 0, 0, 0, extra.crush ?? 0];
}

/** sounds as 8-bit chip blips, generated by ZzFX (MIT) in the browser so no audio files needed */
export const SOUND_PRESETS: Record<SoundName, Note[]> = {
  // two-step "bloop" up a fifth
  open: [{ at: 0, params: chip(440, 0.07, { jump: 220, jumpAt: 0.035 }) }],
  // same bloop, stepping down
  close: [{ at: 0, params: chip(660, 0.07, { jump: -220, jumpAt: 0.035 }) }],
  // crunchy falling sweep, like the window shrinking away
  minimize: [{ at: 0, params: chip(880, 0.1, { slide: -45, crush: 0.2 }) }],
  // crunchy rising sweep for going full screen (and back)
  maximize: [{ at: 0, params: chip(300, 0.1, { slide: 45, crush: 0.2 }) }],
  // classic low double buzz for File not found
  error: [
    { at: 0, params: chip(110, 0.11, { volume: 0.3 }) },
    { at: 0.16, params: chip(110, 0.11, { volume: 0.3 }) },
  ],
  // tiny high click when the JackOS menu opens
  menu: [{ at: 0, params: chip(1200, 0.03, { volume: 0.2 }) }],
  // four-note chip arpeggio for boot, holds the last note
  startup: [
    { at: 0, params: chip(523, 0.09) },
    { at: 0.1, params: chip(659, 0.09) },
    { at: 0.2, params: chip(784, 0.09) },
    { at: 0.3, params: chip(1047, 0.25) },
  ],
};

/** master level on top of each preset's own volume; square waves sound loud, so keep it low and subtle */
export const MASTER_VOLUME = 0.3;

// created on first play so visitors who keep sound off never allocate audio
let audioContext: AudioContext | null = null;
let master: GainNode | null = null;
// each sound is generated once and reused
const buffers = new Map<SoundName, { at: number; buffer: AudioBuffer }[]>();

/** builds (once) the audio buffers for a sound's notes */
function buffersFor(context: AudioContext, name: SoundName) {
  let notes = buffers.get(name);
  if (!notes) {
    notes = SOUND_PRESETS[name].map((note) => {
      const samples = zzfxGenerate(...note.params);
      const buffer = context.createBuffer(1, samples.length, ZZFX_SAMPLE_RATE);
      buffer.getChannelData(0).set(samples);
      return { at: note.at, buffer };
    });
    buffers.set(name, notes);
  }
  return notes;
}

/** play a sound by name, silent if the browser has no Web Audio or blocks it */
export function playSound(name: SoundName): void {
  try {
    // create the context on first use and wake it up if autoplay rules started it suspended
    audioContext ??= new AudioContext();
    if (audioContext.state === "suspended") void audioContext.resume();
    if (!master) {
      master = audioContext.createGain();
      master.gain.value = MASTER_VOLUME;
      master.connect(audioContext.destination);
    }
    // schedule every note relative to now so multi-note sounds play in one go
    const now = audioContext.currentTime;
    for (const note of buffersFor(audioContext, name)) {
      const source = audioContext.createBufferSource();
      source.buffer = note.buffer;
      source.connect(master);
      source.start(now + note.at);
    }
  } catch {
    // no audio support, stay silent
  }
}
